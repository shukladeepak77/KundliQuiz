import { useMemo, useState } from "react";
import { people } from "../data/people";
import type { Person } from "../data/types";

type Props = {
  onPick: (personSlug: string) => void;
};

export default function SearchHome({ onPick }: Props) {
  const [query, setQuery] = useState("");

  const results = useMemo<Person[]>(() => {
    const q = query.trim().toLowerCase();
    if (!q) return people;
    return people.filter((p) => p.name.toLowerCase().includes(q));
  }, [query]);

  return (
    <div className="home">
      <header className="hero">
        <div className="hero-badge">🪔 Dharma Path USA Foundation</div>
        <h1>Kundli Quiz</h1>
        <p className="hero-sub">
          Find a name below to learn that person's Janam Kundli by answering
          questions about it — instead of just scrolling past pages of a PDF.
        </p>
      </header>

      <div className="search-box">
        <input
          type="text"
          inputMode="search"
          autoCapitalize="words"
          placeholder="Search by name…"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          className="search-input"
          aria-label="Search by name"
        />
      </div>

      <div className="section-list">
        {results.length === 0 ? (
          <div className="search-empty">No one matches “{query}” yet.</div>
        ) : (
          results.map((p) => (
            <button key={p.slug} className="section-card" onClick={() => onPick(p.slug)}>
              <div className="section-card-icon">🧑</div>
              <div className="section-card-body">
                <div className="section-card-title">{p.name}</div>
                <div className="section-card-blurb">
                  Lagna: {p.lagna} · {p.sections.reduce((n, s) => n + s.questions.length, 0)} questions
                </div>
              </div>
              <div className="section-card-arrow">→</div>
            </button>
          ))
        )}
      </div>

      <footer className="home-footer">
        Each kundli is sourced from that person's own Honest Diagnostic
        report, generated by Dharma Path USA Foundation. For spiritual
        guidance &amp; educational purposes only.
      </footer>
    </div>
  );
}
